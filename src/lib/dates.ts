/**
 * Small date helpers. Dates in notes are stored as plain calendar days
 * ("2026-12-05", no time or time zone), which is what "due on Friday" means.
 */

/** Today's (or `date`'s) calendar day as "YYYY-MM-DD", in the student's local time. */
export function toISODate(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

/** A calendar day `days` after `from` (negative goes back). */
export function addDays(from: Date, days: number): Date {
  const result = new Date(from);
  result.setDate(result.getDate() + days);
  return result;
}

export function isValidISODate(value: string): boolean {
  return /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(Date.parse(value));
}

/**
 * Whole days from `today` until `isoDate` (0 = today, 1 = tomorrow, -1 = yesterday).
 * Works on calendar days via UTC, so daylight-saving changes can't make it off by one.
 */
export function daysUntil(isoDate: string, today: Date = new Date()): number {
  const [y, m, d] = isoDate.split("-").map(Number);
  const target = Date.UTC(y, m - 1, d);
  const now = Date.UTC(today.getFullYear(), today.getMonth(), today.getDate());
  return Math.round((target - now) / 86_400_000);
}

/** "today", "tomorrow", "in 5 days", "yesterday", "3 days ago". */
export function describeDaysUntil(days: number): string {
  if (days === 0) return "today";
  if (days === 1) return "tomorrow";
  if (days === -1) return "yesterday";
  return days > 0 ? `in ${days} days` : `${-days} days ago`;
}

/** "Fri, Dec 5" (in the student's own language settings). */
export function formatShortDate(isoDate: string): string {
  const [y, m, d] = isoDate.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(undefined, { weekday: "short", month: "short", day: "numeric" });
}
